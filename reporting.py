"""
reporting.py -- generates RESULTS.md, the running scorecard (2026-09-07, PR 6).

WHAT IT IS. A pure renderer, no tool access. The orchestrating session
fetches the account snapshot and Robinhood's own realized P&L / trade
history via the MCP tools and passes them in as JSON; this module folds
them together with trade_log.jsonl and writes RESULTS.md.

RESULTS.md is the "how is the bot doing" document -- a scorecard plus a
trade ledger -- as opposed to TRADE_LOG.md (render_trade_log.py), which is
the raw event feed. Robinhood's numbers are the source of truth for money;
the trade log is the source of truth for *why* each trade was taken.

WHY A SEPARATE COMMIT STEP. The scheduled tasks run in a cloud workspace
that is not a push-enabled git checkout, so RESULTS.md written there is not
automatically on GitHub. Two ways to surface it:
  * the Market-Close task embeds RESULTS.md's scorecard in its notification
    (so you see it even with no git), and
  * `python3 reporting.py --commit` -- run wherever a push-enabled checkout
    exists (an interactive session, or the task IF its container is given
    push credentials) -- does `git add RESULTS.md && git commit && git push`.

INPUTS (all optional; the report degrades to what it's given)
  --now-utc ISO8601
  --realized-json '{"today":..,"week":..,"month":..,"all":..,
                    "trades_week":..,"trades_month":..,"win_rate":..}'
        from get_realized_pnl over day/week/month/all spans + (optionally)
        a per-trade win rate the caller computed from get_pnl_trade_history.
  --closed-trades-json '[{"symbol","option_type","strike","expiration",
        "opened_at","closed_at","entry_price","exit_price","contracts",
        "realized_pnl","exit_reason"}, ...]'
        recent closed trades (from get_pnl_trade_history or reconstructed
        from the log). Drives the ledger and the fallback win rate.
  --account-json '{"total_value","buying_power","options_value",
        "open_positions":[{"symbol","strike","option_type","expiration",
        "quantity","average_price","current_mark"}]}'
  --commit          also git add/commit/push RESULTS.md

USAGE
  python3 reporting.py --now-utc 2026-09-07T20:05:00Z \
      --realized-json '{...}' --closed-trades-json '[...]' --account-json '{...}'
"""
